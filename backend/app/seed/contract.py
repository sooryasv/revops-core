CONTRACT_VERSION = "1.0.0"
TABLES = (
    "organizations", "users", "customers", "invoice_sequences", "deals", "invoices", "invoice_items",
    "payment_orders", "payments", "webhook_events", "audit_logs",
)  # fmt: skip

_ARGON = re.compile(r"\$argon2")


def ai_views_file_text() -> str:
    body = ";\n\n".join(statements(AI_VIEWS_SQL))
    return (
        "-- ai schema views: the AI/agent contract (02 section 3). GENERATED by `export-contract` from app/db/contract_sql.py.\n"
        "-- Run as the owner role (revops_owner) AFTER the public schema and mv_collections_daily exist.\n"
        "-- Every view is security_barrier and fails closed when app.current_org is unset.\n\n"
        f"{body};\n"
    )


async def build_manifest(owner_url: str, *, seed: int, today: date) -> dict[str, Any]:
    engine = create_async_engine(owner_url)
    try:
        async with engine.connect() as conn:
            orgs = (
                await conn.execute(text("SELECT id, name FROM organizations ORDER BY name"))
            ).all()
            manifest: dict[str, Any] = {
                "contract_version": CONTRACT_VERSION, "seed": seed, "today": today.isoformat(), "orgs": {},
                "note": "overdue and outstanding are as of `today`; the ai views use the database clock (IST date).",
            }  # fmt: skip
            for org_id, name in orgs:
                counts = {}
                for table in TABLES:
                    t = Base.metadata.tables[table]
                    key = t.c.id if table == "organizations" else t.c.org_id
                    stmt = select(func.count()).select_from(t).where(key == org_id)
                    counts[table] = int((await conn.execute(stmt)).scalar_one())
                inv = (
                    await conn.execute(
                        text(
                            "SELECT status, count(*) FROM invoices WHERE org_id = :o GROUP BY status ORDER BY status"
                        ),
                        {"o": org_id},
                    )
                ).all()
                money = (
                    await conn.execute(
                        text(
                            "SELECT coalesce(sum(greatest(total_paise - amount_paid_paise, 0)), 0), "
                            "coalesce(sum(greatest(total_paise - amount_paid_paise, 0)) FILTER (WHERE due_date < :today), 0), "
                            "count(*) FILTER (WHERE total_paise > amount_paid_paise AND due_date < :today) "
                            "FROM invoices WHERE org_id = :o AND status = 'issued'"
                        ),
                        {"o": org_id, "today": today},
                    )
                ).one()
                events = (
                    await conn.execute(
                        text(
                            "SELECT processing_status, count(*) FROM webhook_events WHERE org_id = :o "
                            "GROUP BY processing_status ORDER BY processing_status"
                        ),
                        {"o": org_id},
                    )
                ).all()
                poison = (
                    await conn.execute(
                        text(
                            "SELECT id FROM customers WHERE org_id = :o AND notes LIKE 'SYSTEM:%'"
                        ),
                        {"o": org_id},
                    )
                ).scalar_one_or_none()
                manifest["orgs"][name] = {
                    "org_id": str(org_id),
                    "row_counts": counts,
                    "invoices_by_status": {s: int(n) for s, n in inv},
                    "outstanding_paise": int(money[0]),
                    "overdue_paise": int(money[1]),
                    "overdue_invoices": int(money[2]),
                    "visible_webhook_events_by_status": {s: int(n) for s, n in events},
                    "poison_note_customer_id": str(poison) if poison else None,
                }
    finally:
        await engine.dispose()
    return manifest


async def _pg_dump(owner_url: str, *args: str) -> str:
    url = make_url(owner_url)
    env = {**os.environ, "PGPASSWORD": url.password or ""}
    cmd = [
        "pg_dump", "-h", url.host or "127.0.0.1", "-p", str(url.port or 5432), "-U", url.username or "",
        "--no-owner", *args, url.database or "",
    ]  # fmt: skip
    proc = await asyncio.create_subprocess_exec(
        *cmd, env=env, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE
    )
    out, err = await proc.communicate()
    if proc.returncode != 0:
        raise RuntimeError(f"pg_dump failed: {err.decode()[:500]}")
    return out.decode()


def _write_all(out_dir: Path, files: dict[str, str]) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out_dir / name).write_text(content)
    return list(files)


def _roles_file(out_dir: Path, roles_sql: Path) -> dict[str, str]:
    """roles.sql is hand-written and lives in contract/; copy it only when exporting from somewhere else."""
    if roles_sql.resolve() == (out_dir / "roles.sql").resolve():
        return {}
    return {"roles.sql": roles_sql.read_text()}


async def export_contract(
    out_dir: Path,
    owner_url: str,
    *,
    seed: int,
    today: date,
    roles_sql: Path,
    openapi: dict[str, Any],
) -> list[str]:
    files: dict[str, str] = {"CONTRACT_VERSION": CONTRACT_VERSION + "\n"}
    files.update(_roles_file(out_dir, roles_sql))
    files["ai_views.sql"] = ai_views_file_text()
    snapshot = await _pg_dump(owner_url, "--schema-only", "-n", "public", "-n", "ai")
    if "CREATE SCHEMA ai;" not in snapshot:
        raise RuntimeError("unexpected pg_dump output: no CREATE SCHEMA ai")
    # roles.sql already creates the schema (and grants USAGE on it), so the snapshot must tolerate that.
    files["schema_snapshot.sql"] = re.sub(
        r"^CREATE SCHEMA (\w+);$", r"CREATE SCHEMA IF NOT EXISTS \1;", snapshot, flags=re.MULTILINE
    )
    seed_dump = await _pg_dump(
        owner_url, "--data-only", "--column-inserts", "-n", "public", "-T", "public.alembic_version"
    )
    if _ARGON.search(seed_dump):
        raise RuntimeError(
            "the seed dump contains argon2 hashes: seed with --no-login before exporting (no credentials in contract/)"
        )
    files["seed_demo.sql"] = seed_dump
    manifest = await build_manifest(owner_url, seed=seed, today=today)
    files["seed_manifest.json"] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    files["openapi.json"] = json.dumps(openapi, indent=2, sort_keys=True) + "\n"
    files["README.md"] = README
    return _write_all(out_dir, files)


README = """# Contract package (version in CONTRACT_VERSION)

Everything Project 2 needs from Project 1. Treat this folder as read-only; a needed change is logged in P2's
`.build/SPEC_ISSUES.md` and decided by the human.

| File | What it is |
|---|---|
| `CONTRACT_VERSION` | semantic version of the contract (02) |
| `roles.sql` | creates `revops_owner`, `revops_app`, `ai_reader`, schemas and default privileges (run once, as superuser) |
| `schema_snapshot.sql` | `pg_dump --schema-only` of schemas `public` and `ai` (tables, the materialized view, the refresh function, the ai views, grants) |
| `ai_views.sql` | the exact DDL of the seven `ai` views (already contained in the snapshot; use it to re-apply or review them) |
| `seed_demo.sql` | data-only dump (`--column-inserts`) of the deterministic demo dataset. Users cannot log in (no password hashes) |
| `seed_manifest.json` | expected counts per table per organisation, overdue totals, visible webhook events (computed by SQL) |
| `openapi.json` | the P1 REST API |

## Load into a fresh PostgreSQL (16 or 17)

```bash
createdb revops
psql -v ON_ERROR_STOP=1 -d revops -v dbname=revops -v owner_password=... -v app_password=... -v ai_password=... \\
     -f roles.sql                                  # as a superuser
PGPASSWORD=<owner_password> psql -v ON_ERROR_STOP=1 -h <host> -U revops_owner -d revops -f schema_snapshot.sql
PGPASSWORD=<owner_password> psql -v ON_ERROR_STOP=1 -h <host> -U revops_owner -d revops -f seed_demo.sql
PGPASSWORD=<owner_password> psql -h <host> -U revops_owner -d revops -c "REFRESH MATERIALIZED VIEW public.mv_collections_daily"
```

The snapshot creates the materialized view empty (`WITH NO DATA`), and `REFRESH ... CONCURRENTLY` (what
`public.refresh_collections_mv()` runs) refuses an unpopulated view, so the first fill is a plain refresh by the owner.
After that, use `SELECT public.refresh_collections_mv()`.

## Read as the agent role

```sql
-- as ai_reader, inside a transaction:
SELECT set_config('app.current_org', '<org uuid from seed_manifest.json>', true);
SELECT * FROM ai.v_receivables_summary;
```

With the setting unset every `ai` view returns zero rows. `ai_reader` has no access to the `public` schema.

## Notes

* Overdue values depend on the date: the views use the database clock (IST calendar date). The manifest records the
  `today` the data was generated for; regenerate with `seed-demo --reset --seed 42 --today YYYY-MM-DD` for a fixed day.
* `ai.v_webhook_health` aggregates the last 7 days (the contract's `event_count_7d`).
"""
